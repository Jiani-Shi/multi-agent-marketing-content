# src/prompts/wechat.py

from .base import BasePrompt


class WechatPrompt(BasePrompt):
    """公众号平台 Prompt 模板"""

    def __init__(self):
        super().__init__()
        self.platform = "wechat"
        self.min_content_length = 800
        self.max_content_length = 2000

    def get_platform_rules(self) -> str:
        return """
公众号推文的核心特征：
1. 标题有深度感：常用提问式或对比式标题（如"用了XX，我再也没..."）
2. 开头有叙事感：从个人故事或场景切入，而非直接介绍产品
3. 结构清晰：用"01 / 02 / 03"或小标题分节
4. 信息密度高：内容要有深度，提供足够的背景知识和产品信息
5. 作者署名：开头有"文 | 作者名"的格式
6. 真诚推荐：语气真诚克制，不以博主身份强推
7. 商业说明：文末标注商业合作声明（如适用）
"""

    def get_few_shot_instruction(self) -> str:
        return """【关于爆款参考的重要说明】
以下是为您提供的公众号爆款推文示例。公众号的特点是"深度内容+真诚叙事"。
请重点学习示例中的以下要素：
1. 标题如何体现深度感（提问式？对比式？）
2. 开头如何用个人故事自然引入
3. 正文的结构如何分层（01/02/03分段）
4. 如何在深度叙述中自然融入产品推荐
5. 结尾如何收束全文并引导行动

请模仿这些要素来创作，但不要复制示例中的具体品牌名或产品名。
"""

    def get_negative_constraints(self) -> str:
        return """【公众号平台禁止事项】
1. 禁止过度夸张：不要使用"史上最好""绝对第一""无人能比"等绝对化用语
2. 禁止虚假宣传：不要编造不存在的功效、数据或用户评价
3. 禁止违规词汇：不要包含平台违禁词、敏感词或低俗内容
4. 禁止抄袭：不要复制参考示例中的具体内容，只学习其结构和风格
5. 禁止硬广语气：公众号读者偏好深度阅读，避免像广告软文一样强行推销
6. 禁止信息过载：不要堆砌信息，保持叙述的连贯性和可读性
"""

    def get_cot_steps(self) -> str:
        return """请按以下步骤生成公众号推文：
1. 设计一个有代入感的个人故事或场景作为开头
2. 引出产品，自然过渡到产品介绍
3. 深入分析产品的核心优势和适用人群
4. 提供使用案例或效果展示
5. 以真诚的推荐语收尾
6. 添加商业合作声明（如适用）"""

    def get_output_format(self) -> str:
        return """请返回 JSON 格式：
{
    "title": "推文标题（有深度感，20字以内）",
    "content": "完整推文正文（800-2000字，含署名和分段结构）"
}"""