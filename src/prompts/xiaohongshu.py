from .base import BasePrompt


class XiaohongshuPrompt(BasePrompt):
    """小红书平台 Prompt 模板"""

    def __init__(self):
        super().__init__()
        self.platform = "xiaohongshu"
        self.min_content_length = 300
        self.max_content_length = 800

    def get_platform_rules(self) -> str:
        return """
小红书种草笔记的核心特征：
1. 标题要吸引眼球：常用"数字+关键词"（如"3天白一个度"），配合"｜"分隔符
2. 正文以个人真实体验开头：用第一人称讲述，营造"姐妹分享"的氛围
3. 段落分明：用短段落+emoji图标增加可读性
4. 种草语气：真诚分享而非硬推销，多用"真的""太..."等情感表达
5. 收藏价值：提供实用信息（如使用技巧、成分解析），增加收藏率
6. 话题标签：文末添加5-8个相关话题标签（以#开头）
"""

    def get_few_shot_instruction(self) -> str:
        return """【关于爆款参考的重要说明】
以下是为您提供的小红书爆款笔记示例。小红书的特点是"真实体验感+收藏价值"。
请重点学习示例中的以下要素：
1. 标题如何用"数字+关键词"吸引点击（如"3天白一个度｜美白精华测评"）
2. 开头如何营造"姐妹真心分享"的氛围
3. 正文如何平衡"个人体验"和"实用信息"
4. 如何通过提供额外价值（技巧、搭配、清单）增加收藏率

请模仿这些要素来创作，但不要复制示例中的具体品牌名或产品名。
"""

    def get_negative_constraints(self) -> str:
        return """【小红书平台禁止事项】
1. 禁止过度夸张：不要使用"史上最好""绝对第一""无人能比"等绝对化用语
2. 禁止虚假宣传：不要编造不存在的功效、数据或用户评价
3. 禁止违规词汇：不要包含平台违禁词、敏感词或低俗内容
4. 禁止抄袭：不要复制参考示例中的具体内容，只学习其结构和风格
5. 禁止硬广语气：不要像电视购物那样强行推销，保持"真诚种草"的语气
6. 禁止诱导互动：不要使用"点赞暴富""收藏变美"等诱导性话术
"""

    def get_cot_steps(self) -> str:
        return """请按以下步骤生成小红书笔记：
1. 以一个真实使用场景或个人痛点作为开头
2. 描述产品带来的改变（突出"真实体验感"）
3. 补充产品的核心优势（成分/功效/性价比）
4. 给出实用的使用建议或搭配方案（增加收藏价值）
5. 结尾引导互动（提问/邀请讨论）"""

    def get_output_format(self) -> str:
        return """请返回 JSON 格式：
{
    "title": "笔记标题（含emoji和｜分隔符，25字以内）",
    "content": "完整种草正文（300-800字，含emoji和话题标签）"
}"""