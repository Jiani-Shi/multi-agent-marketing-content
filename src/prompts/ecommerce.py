# src/prompts/ecommerce.py

from .base import BasePrompt


class EcommercePrompt(BasePrompt):
    """电商平台（淘宝/京东）Prompt 模板"""

    def __init__(self):
        super().__init__()
        self.platform = "ecommerce"
        self.min_content_length = 200
        self.max_content_length = 500

    def get_platform_rules(self) -> str:
        return """
电商详情页文案的核心特征：
1. 开头建立信任：用数据、认证或名人背书开场
2. 痛点-解决方案结构：明确用户痛点，提供产品作为解决方案
3. 卖点分条列举：用数字或图标分条展示核心卖点
4. 参数表格化：产品规格、成分、材质等信息用列表清晰呈现
5. 用户评价引入：穿插真实用户评价（可模拟）
6. 售后保障信息：明确退换货政策、质保期限等
7. 行动号召：结尾有明确的购买引导（价格/优惠/购买按钮）
8. 风格偏理性：电商文案偏重说服力，而非纯粹情绪化
"""

    def get_few_shot_instruction(self) -> str:
        return """【关于爆款参考的重要说明】
以下是为您提供的电商爆款详情页示例。电商文案的特点是"理性说服+信任建立"。
请重点学习示例中的以下要素：
1. 开头如何快速建立信任感（数据？认证？用户口碑？）
2. 如何将产品卖点分条清晰罗列
3. 如何融入用户评价来增强说服力
4. 结尾如何设计购买引导

请模仿这些要素来创作，但不要复制示例中的具体品牌名或产品名。
"""

    def get_negative_constraints(self) -> str:
        return """【电商平台禁止事项】
1. 禁止过度夸张：不要使用"史上最好""绝对第一""无人能比"等绝对化用语
2. 禁止虚假宣传：不要编造不存在的功效、数据或用户评价
3. 禁止违规词汇：不要包含平台违禁词、敏感词或低俗内容
4. 禁止抄袭：不要复制参考示例中的具体内容，只学习其结构和风格
5. 禁止价格误导：不要虚构原价或使用"限时"制造虚假紧迫感
6. 禁止功效承诺：不要做出无法兑现的功效承诺（尤其是保健品/护肤品）
"""

    def get_cot_steps(self) -> str:
        return """请按以下步骤生成电商详情页文案：
1. 分析目标用户的核心购买顾虑是什么
2. 设计建立信任感的开头
3. 分条罗列产品的核心卖点
4. 补充产品参数和规格信息
5. 设置用户评价参考和售后保障
6. 结尾引导购买"""

    def get_output_format(self) -> str:
        return """请返回 JSON 格式：
{
    "title": "商品标题（含关键词和促销信息，30字以内）",
    "content": "完整详情页文案（200-500字，含分条卖点和用户评价）"
}"""