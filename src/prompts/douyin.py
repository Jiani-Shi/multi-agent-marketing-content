# src/prompts/douyin.py

from .base import BasePrompt


class DouyinPrompt(BasePrompt):
    """抖音平台 Prompt 模板"""

    def __init__(self):
        super().__init__()
        self.platform = "douyin"
        self.min_content_length = 100
        self.max_content_length = 300

    def get_platform_rules(self) -> str:
        return """
抖音短视频文案的核心特征：
1. 开头3秒必须抓住注意力：用提问句、惊叹句或场景代入来开场
2. 语速快、节奏感强：文案要像说话一样自然，多用短句
3. 口语化表达：多用"姐妹们""兄弟们""谁懂啊"等口头禅
4. 情绪饱满：表达强烈的情感态度（惊叹、后悔、兴奋、感动）
5. 互动引导：结尾要有明确的行动号召（点赞、评论、购买）
6. 话题标签：结尾添加3-5个相关标签（用#号）
7. 时长约束：文案对应30-60秒口播
"""

    def get_few_shot_instruction(self) -> str:
        return """【关于爆款参考的重要说明】
以下是为您提供的抖音爆款文案示例。抖音文案的特点是"前3秒抓人、口语化强、情绪饱满"。
请重点学习示例中的以下要素：
1. 开头如何瞬间抓住注意力（提问？惊叹？场景代入？）
2. 如何用口语化的方式讲述产品体验
3. 情绪节奏如何推进（从痛点→解决方案→行动号召）
4. 如何自然地融入话题标签

请模仿这些要素来创作，但不要复制示例中的具体品牌名或产品名。
"""

    def get_negative_constraints(self) -> str:
        return """【抖音平台禁止事项】
1. 禁止过度夸张：不要使用"史上最好""绝对第一""无人能比"等绝对化用语
2. 禁止虚假宣传：不要编造不存在的功效、数据或用户评价
3. 禁止违规词汇：不要包含平台违禁词、敏感词或低俗内容
4. 禁止抄袭：不要复制参考示例中的具体内容，只学习其结构和风格
5. 禁止诱导违规互动：不要使用"转发到三个群""不转不是中国人"等诱导性话术
6. 禁止过度营销：不要全文只讲产品，需要有真实体验或场景代入
"""

    def get_cot_steps(self) -> str:
        return """请按以下步骤生成抖音文案：
1. 思考目标用户的核心痛点是什么
2. 设计一个能瞬间抓住眼球的开场钩子（3秒内）
3. 用口语化的方式讲述产品带来的改变
4. 设计结尾的行动号召（引导点赞/评论/购买）
5. 添加合适的话题标签"""

    def get_output_format(self) -> str:
        return """请返回 JSON 格式：
{
    "title": "视频标题（含表情符号，15字以内）",
    "content": "完整口播文案（100-300字，含表情符号和话题标签）"
}"""